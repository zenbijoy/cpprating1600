/**
 * Returns a random contest from the curated pool, with optional platform / division filtering.
 */
export function getRandomContest(filter?: {
  platform?: ContestPlatform | 'All';
  division?: string;
}): ArenaContestItem {
  let pool = CURATED_CONTESTS_DATASET;
  if (filter?.platform && filter.platform !== 'All') {
    pool = pool.filter((c) => c.platform === filter.platform);
  }
  if (filter?.division && filter.division !== 'All') {
    pool = pool.filter((c) => c.division === filter.division);
  }
  if (pool.length === 0) pool = CURATED_CONTESTS_DATASET;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
